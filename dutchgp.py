v2["base_score"] = 0.8 * v2["model_score"] + 0.2 * v2["zandvoort_history"]

# Rank-normalise both signals before blending so neither dominates by scale
v2["base_rank_score"] = v2["base_score"].rank()
v2["grid_rank_score"] = v2["grid_position"].rank()
v2["v2_score"] = alpha * v2["grid_rank_score"] + (1 - alpha) * v2["base_rank_score"]

v2 = v2.sort_values("v2_score").reset_index(drop=True)
v2["v2_predicted_rank"] = np.arange(1, len(v2) + 1)

